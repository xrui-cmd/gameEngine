#ifndef __UPDATECONTEXT_H__
#define __UPDATECONTEXT_H__

// ============================================================
// UpdateContext：一次 update 调用所需的「世界上下文」
// ============================================================
//
// 为什么需要它？
//   实体每步需要的外部信息不止 deltaTime：玩家要读实时键盘状态，
//   移动边界与金币重生又要视口尺寸。若把这些字段直接铺在 update
//   的参数列表里，接口会越加越长；而且每加一个字段，所有实体的
//   函数签名都要同步修改。
//
//   「上下文结构体」模式把一步的稳定环境信息打成一个只读包裹：
//   GameDev 在每个渲染帧装配一次，按值传给当前场景，再由场景分发
//   给场上实体；同一渲染帧内的所有固定步共享同一份上下文。
//   将来新增「鼠标位置」「摄像机偏移」等字段时，只需扩展本结构体
//   并在装配处填充，实体一侧的调用形式保持不变。
//
// 使用约定：
//   - 结构体只携带「本帧快照」，实体不得把内部指针跨帧缓存：
//     keyboard 指向 SDL 内部数组，其内容由 SDL 每帧刷新
//   - 按值传递（只有几个字段，很小），调用方不必管理生命周期
//   - input 指向宿主装配的输入系统（按渲染帧采样一次，边沿在整帧内可见）；
//     新代码一律通过它查询动作，旧代码的 keyboard 直读路径逐步迁移
// ============================================================

class Input; // 前置声明：本头文件只保存 Input 指针，无需引入 Input.h 全量定义

struct UpdateContext
{
    float deltaTime;      // 固定步长（秒）：逻辑与计时的唯一时间基准（目前为 1/120）
    const bool* keyboard; // 过渡期保留（M1 迁移后移除）：SDL 键盘状态数组指针；新代码改用 input
    float viewportWidth;  // 视口（窗口）逻辑宽度（像素），边界/重生范围的计算基准
    float viewportHeight; // 视口（窗口）逻辑高度（像素），同上

    // 输入系统快照指针（借用不持有，所有权在宿主）：本帧已被采样过一次，
    // 同帧所有固定步共享同一份边沿状态。nullptr = 本帧无输入系统（旧调用方
    // 兼容）；实体应做空指针判断或退用 keyboard。刻意追加在结构末尾：
    // 前四个字段顺序不变，既有聚合初始化代码无需修改
    const Input* input = nullptr;
};

#endif // !__UPDATECONTEXT_H__
