#ifndef __RECT_H__
#define __RECT_H__

#include <SDL3/SDL.h>

// ============================================================
// AABB（Axis-Aligned Bounding Box，轴对齐包围盒）相交判定工具
// ============================================================
//
// 原理（2D 分离轴思想）：
// 两个矩形相交，等价于它们在 X 轴上的投影区间相交，且
// 在 Y 轴上的投影区间也相交。
//
// 反过来推理更好用：只要有一根轴上的投影不重叠，
// 两个矩形就一定不相交。对 SDL_FRect 来说：
//
//   X 轴不重叠：a 完全在 b 左侧，或 b 完全在 a 左侧
//               即 a.x + a.w <= b.x  或  b.x + b.w <= a.x
//
//   Y 轴不重叠：a 完全在 b 上方，或 b 完全在 a 上方
//               即 a.y + a.h <= b.y  或  b.y + b.h <= a.y
//
// 因此只要上述条件之一成立，就可以立刻判定"不相交"。
// 这里用 <= 而不是 <，约定"边界刚好贴在一起"不算碰撞。
//
// 适用前提：两个矩形都不能旋转（轴对齐）。这也正是我们
// 这个小游戏里玩家和金币都是方块、不做旋转的直接原因。
// ============================================================

// 判断两个 SDL_FRect 是否重叠。返回 true 表示发生碰撞。
inline bool rectsOverlap(const SDL_FRect& a, const SDL_FRect& b)
{
    // 条件一：X 轴方向完全分离（a 在 b 左侧，或 b 在 a 左侧）
    if (a.x + a.w <= b.x || b.x + b.w <= a.x)
    {
        return false; // X 轴已分离，两个矩形一定不相交，提前返回
    }

    // 条件二：Y 轴方向完全分离（a 在 b 上方，或 b 在 a 上方）
    if (a.y + a.h <= b.y || b.y + b.h <= a.y)
    {
        return false; // Y 轴已分离，同样判定为不相交
    }

    // 两根轴上的投影都重叠，说明两个矩形相交，发生碰撞
    return true;
}

#endif // !__RECT_H__
